const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const { installFixtures } = require('./verify-workspace-layout.cjs');
const assert = require('node:assert/strict');
const root=(process.env.UI_OUTPUT_DIR || require('path').resolve(__dirname, '../playwright-screenshots/layout')) + '/';
const baseUrl=process.env.UI_BASE_URL || 'http://127.0.0.1:5174';
require('fs').mkdirSync(root,{recursive:true});
(async()=>{
 const browser=await chromium.launch({headless:true,...(process.env.UI_BROWSER_CHANNEL ? {channel:process.env.UI_BROWSER_CHANNEL} : {})});
 const context=await browser.newContext({viewport:{width:1440,height:900}});
 await installFixtures(context);
 const page=await context.newPage();
 await page.goto(baseUrl+'/dashboard',{waitUntil:'domcontentloaded'});
 await page.locator('.sider-brand').waitFor();
 const width=()=>page.locator('.sider').evaluate(el=>Math.round(el.getBoundingClientRect().width));
 assert.equal(await width(),232);
 await page.locator('.navigation-toggle').click();
 await page.waitForTimeout(250);
 assert.equal(await width(),64);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('.sider-brand').waitFor();
 assert.equal(await width(),64);
 await page.locator('.navigation-toggle').click();
 await page.waitForTimeout(250);
 assert.equal(await width(),232);
 await page.setViewportSize({width:1024,height:900});
 await page.waitForTimeout(250);
 assert.equal(await width(),64);
 await page.locator('.navigation-toggle').click();
 await page.waitForTimeout(250);
 assert.equal(await width(),232);
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(250);
 await page.locator('.navigation-toggle').click();
 const dialog=page.getByRole('dialog',{name:'主导航'});
 await dialog.waitFor({state:'visible'});
 assert.equal(await page.locator('.header').evaluate(el=>el.inert),true);
 await page.waitForTimeout(250);
 assert.equal(await page.evaluate(()=>document.activeElement?.getAttribute('aria-label')),'关闭导航');
 await page.keyboard.press('Shift+Tab');
 assert.equal(await page.evaluate(()=>!!document.activeElement.closest('#workspace-navigation')),true);
 await page.keyboard.press('Escape');
 await dialog.waitFor({state:'hidden'});
 assert.equal(await page.locator('.navigation-toggle').evaluate(el=>el===document.activeElement),true);
 await page.locator('.navigation-toggle').click();
 await dialog.getByText('项目管理',{exact:true}).click();
 await page.waitForURL('**/projects');
 assert.equal(await page.locator('.main-layout').evaluate(el=>el.classList.contains('mobile-nav-open')),false);
 await page.locator('.navigation-toggle').click();
 await page.screenshot({path:root+'navigation-mobile.png'});
 await page.keyboard.press('Escape');
 await page.goto(baseUrl+'/testcases',{waitUntil:'domcontentloaded'});
 await page.setViewportSize({width:1440,height:900});
 const separator=page.getByRole('separator',{name:'调整目录宽度'});
 await separator.waitFor({state:'visible'});
 const start=Number(await separator.getAttribute('aria-valuenow'));
 await separator.focus();
 await page.keyboard.press('ArrowRight');
 assert.equal(Number(await separator.getAttribute('aria-valuenow')),start+16);
 const bounds=await separator.boundingBox();
 await page.mouse.move(bounds.x+2,bounds.y+20);
 await page.mouse.down();
 await page.mouse.move(bounds.x+42,bounds.y+20);
 await page.mouse.up();
 assert.equal(Number(await separator.getAttribute('aria-valuenow')),start+56);
 await page.locator('.theme-switch-button').click();
 await page.waitForTimeout(300);
 assert.equal(await page.locator('html').getAttribute('data-theme'),'black');
 const bg=await page.locator('.sider').evaluate(el=>getComputedStyle(el).backgroundColor);
 assert.notEqual(bg,'rgb(255, 255, 255)');
 await page.screenshot({path:root+'testcases-dark.png'});
 await page.locator('.theme-switch-button').click();
 assert.equal(await page.locator('html').getAttribute('data-theme'),null);
 await page.getByRole('button',{name:'账户菜单'}).click();
 await page.getByText('个人中心',{exact:true}).last().waitFor({state:'visible'});
 const publicContext=await browser.newContext({viewport:{width:390,height:844}});
 await installFixtures(publicContext,{authenticated:false});
 const publicPage=await publicContext.newPage();
 await publicPage.goto(baseUrl+'/login',{waitUntil:'domcontentloaded'});
 const loginForm=publicPage.locator('.feice-auth-card');
 await loginForm.waitFor({state:'visible'});
 const loginBounds=await loginForm.boundingBox();
 assert(loginBounds.x>=0 && loginBounds.x+loginBounds.width<=390);
 await publicPage.getByLabel('密码',{exact:true}).fill('visibility-check');
 const passwordToggle=publicPage.getByRole('button',{name:'显示密码',exact:true});
 await passwordToggle.focus();
 await publicPage.keyboard.press('Enter');
 assert.equal(await publicPage.locator('#login-password').getAttribute('type'),'text');
 await publicPage.screenshot({path:root+'login-form-mobile.png'});
 await publicPage.getByRole('link',{name:/立即注册/}).click();
 await publicPage.waitForURL('**/register');
 await publicPage.locator('.feice-auth-form').waitFor();
 assert.equal(await publicPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 console.log('PASS: desktop collapse persistence, tablet expand, mobile drawer, inert background, focus trap, Escape focus restoration, route close, keyboard resize, drag delta, theme switch, account menu');
 console.log('PASS: mobile inline login form bounds, keyboard password visibility, registration navigation and width');
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
